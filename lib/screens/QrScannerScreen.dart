
import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:mobile_scanner/mobile_scanner.dart';
import 'package:provider/provider.dart';
import 'package:visitor_management_application/screens/visitor_details_screen.dart';

import '../Color.dart';
import '../models/visitor.dart';
import '../providers/visitor_provider.dart';

class QRScannerScreen extends StatefulWidget {
  final bool isActive;
  const QRScannerScreen({
    super.key,
    this.isActive = true,
  });

  @override
  State<QRScannerScreen> createState() => _QRScannerScreenState();
}

class _QRScannerScreenState extends State<QRScannerScreen>
    with WidgetsBindingObserver {
  late MobileScannerController _scannerController =
  MobileScannerController(
    detectionSpeed: DetectionSpeed.noDuplicates,
  );

  bool _isProcessing = false;

  bool _appResumed = true;
  bool _scannerStarted = false;

  @override
  void initState() {
    super.initState();

    WidgetsBinding.instance.addObserver(this);

    _scannerController = MobileScannerController(
      autoStart: false,
      detectionSpeed: DetectionSpeed.noDuplicates,
      facing: CameraFacing.back,
    );

    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) {
        _syncCamera();
      }
    });
  }

  @override
  void didUpdateWidget(covariant QRScannerScreen oldWidget) {
    super.didUpdateWidget(oldWidget);

    if (oldWidget.isActive != widget.isActive) {
      _syncCamera();
    }
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    _appResumed = state == AppLifecycleState.resumed;
    _syncCamera();
  }

  Future<void> _syncCamera() async {
    if (!mounted) return;

    final shouldRun = widget.isActive && _appResumed;

    try {
      if (shouldRun && !_scannerStarted) {
        _scannerStarted = true;
        await _scannerController.start();
      } else if (!shouldRun && _scannerStarted) {
        _scannerStarted = false;
        await _scannerController.stop();
      }
    } catch (e) {
      _scannerStarted = false;
      debugPrint('Scanner camera error: $e');
    }
  }

  @override
  void dispose() {
    WidgetsBinding.instance.removeObserver(this);
    _scannerController.dispose();
    super.dispose();
  }

  Future<void> _onDetect(BarcodeCapture capture) async {
    if (_isProcessing) return;

    String? scannedValue;

    for (final barcode in capture.barcodes) {
      final value = barcode.rawValue;
      if (value != null && value.isNotEmpty) {
        scannedValue = value;
        break;
      }
    }

    if (scannedValue == null) return;

    // Only accept QR codes generated by this app.
    if (!scannedValue.startsWith('VISITOR:')) {
      await _showError('Invalid visitor QR code');
      return;
    }

    final visitorId =
    scannedValue.substring('VISITOR:'.length).trim();

    if (visitorId.isEmpty ||
        !RegExp(r'^[a-zA-Z0-9_-]+$').hasMatch(visitorId)) {
      await _showError('Invalid visitor ID');
      return;
    }

    setState(() => _isProcessing = true);
    await _scannerController.stop();

    final provider = context.read<VisitorProvider>();
    final VisitorModel? visitor =
    await provider.fetchVisitorById(visitorId);

    if (!mounted) return;

    if (visitor == null) {
      await _showError(
        provider.visitorLookupError ??
            'Unable to retrieve visitor details',
      );
    } else {
      await Navigator.push(
        context,
        MaterialPageRoute(
          builder: (_) => VisitorDetailsScreen(
            visitor: visitor,
          ),
        ),
      );
    }

    if (!mounted) return;

    setState(() => _isProcessing = false);
    await _scannerController.start();
  }

  Future<void> _showError(String message) async {
    if (_isProcessing || !mounted) return;

    setState(() => _isProcessing = true);
    await _scannerController.stop();

    if (!mounted) return;

    await showDialog<void>(
      context: context,
      builder: (dialogContext) => AlertDialog(
        title: const Text('QR Scan Failed'),
        content: Text(message),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(dialogContext),
            child: const Text('Try Again'),
          ),
        ],
      ),
    );

    if (!mounted) return;

    setState(() => _isProcessing = false);
    await _scannerController.start();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: RequiredColors.Background,
      appBar: AppBar(
        backgroundColor: Colors.white,
        surfaceTintColor: Colors.transparent,
        automaticallyImplyLeading: false,
        title: Text(
          'Scan Visitor QR',
          style: GoogleFonts.poppins(
            color: RequiredColors.Charcoal,
            fontSize: 18,
            fontWeight: FontWeight.w600,
          ),
        ),
      ),
      body: Column(
        children: [
          Padding(
            padding: const EdgeInsets.all(20),
            child: Text(
              'Position the visitor QR code inside the frame',
              textAlign: TextAlign.center,
              style: GoogleFonts.poppins(
                fontSize: 13,
                color: RequiredColors.Secondary_Gray,
              ),
            ),
          ),

          Expanded(
            child: Padding(
              padding: const EdgeInsets.symmetric(
                horizontal: 20,
              ),
              child: ClipRRect(
                borderRadius: BorderRadius.circular(22),
                child: Stack(
                  fit: StackFit.expand,
                  children: [
                    MobileScanner(
                      controller: _scannerController,
                      onDetect: _onDetect,
                    ),

                    Center(
                      child: Container(
                        width: 245,
                        height: 245,
                        decoration: BoxDecoration(
                          borderRadius: BorderRadius.circular(22),
                          border: Border.all(
                            color: RequiredColors.Primary_Gold,
                            width: 3,
                          ),
                        ),
                      ),
                    ),

                    if (_isProcessing)
                      Container(
                        color: Colors.black54,
                        child: Center(
                          child: Column(
                            mainAxisSize: MainAxisSize.min,
                            children: [
                              const CircularProgressIndicator(
                                color: RequiredColors.Primary_Gold,
                              ),
                              const SizedBox(height: 18),
                              Text(
                                'Fetching Visitor Details...',
                                style: GoogleFonts.poppins(
                                  color: Colors.white,
                                  fontSize: 14,
                                  fontWeight: FontWeight.w500,
                                ),
                              ),
                            ],
                          ),
                        ),
                      ),
                  ],
                ),
              ),
            ),
          ),

          const SizedBox(height: 24),
        ],
      ),
    );
  }
}
